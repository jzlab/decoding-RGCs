"""Synthetic data generators with analytic answers, for testing the spectral module.

Nothing here imports the retina or diffusion code.  Every generator has a closed
form that the tests compare the estimator against, so a test failure points at
the estimator rather than at a reference implementation that might itself be
wrong.

Normalization convention.  :func:`analysis.spectral_fillin.preprocess` divides by
``sqrt(U * H * W)``, so an unwindowed field generated by :func:`gaussian_field`
with power spectrum ``P`` satisfies ``E|Xhat(f)|^2 = P(f)`` exactly.  Every
analytic prediction below is written in those units.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np

__all__ = [
    "frequency_grid",
    "power_law_spectrum",
    "gaussian_blur_transfer",
    "dog_transfer",
    "gaussian_field",
    "DiagonalPosterior",
    "make_diagonal_posterior",
    "DensePosterior",
    "make_downsampling_posterior",
]


def frequency_grid(shape: tuple[int, int]) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Build the FFT frequency grids for an image shape.

    Args:
        shape (tuple[int, int]): Image shape as ``(height, width)``.

    Returns:
        tuple[numpy.ndarray, numpy.ndarray, numpy.ndarray]: Vertical frequency,
        horizontal frequency, and radial frequency, each shaped like the image
        and in cycles per pixel.
    """
    height, width = shape
    f_y, f_x = np.meshgrid(np.fft.fftfreq(height), np.fft.fftfreq(width), indexing="ij")
    return f_y, f_x, np.hypot(f_y, f_x)


def power_law_spectrum(shape: tuple[int, int], exponent: float = 2.0, f_knee: float = 0.01) -> np.ndarray:
    """Build a radially symmetric power-law power spectrum.

    The spectrum is ``(f + f_knee)^-exponent``, softened at the origin so that DC
    stays finite.  DC is excluded from every analysis anyway, but a finite value
    keeps the dense covariance in :func:`make_downsampling_posterior` positive
    definite and well conditioned.

    Args:
        shape (tuple[int, int]): Image shape as ``(height, width)``.
        exponent (float): Power-law exponent; ``2.0`` gives the ``1/f^2`` spectrum
            that is the usual stand-in for natural image statistics.
        f_knee (float): Softening frequency in cycles per pixel.

    Returns:
        numpy.ndarray: Power spectrum shaped like the image, symmetric under
        ``f -> -f`` as a real field's spectrum must be.
    """
    _, _, f = frequency_grid(shape)
    return (f + f_knee) ** (-float(exponent))


def gaussian_blur_transfer(shape: tuple[int, int], sigma_pixels: float) -> np.ndarray:
    """Build the transfer function of an isotropic Gaussian blur.

    Args:
        shape (tuple[int, int]): Image shape as ``(height, width)``.
        sigma_pixels (float): Gaussian standard deviation in pixels.

    Returns:
        numpy.ndarray: Real, non-negative, ``f -> -f`` symmetric transfer function.
    """
    _, _, f = frequency_grid(shape)
    return np.exp(-2.0 * (np.pi * f * float(sigma_pixels)) ** 2)


def dog_transfer(
    shape: tuple[int, int], sigma_center: float, sigma_surround: float, surround_strength: float = 0.5
) -> np.ndarray:
    """Build the transfer function of a difference-of-Gaussians receptive field.

    This is the bandpass analogue of :func:`gaussian_blur_transfer` and is the
    closer stand-in for a retinal centre-surround filter: it suppresses low
    frequencies as well as high ones, so the fill-in curve is non-monotonic.

    Args:
        shape (tuple[int, int]): Image shape as ``(height, width)``.
        sigma_center (float): Centre Gaussian standard deviation in pixels.
        sigma_surround (float): Surround Gaussian standard deviation in pixels.
        surround_strength (float): Surround weight relative to the centre.

    Returns:
        numpy.ndarray: Real, ``f -> -f`` symmetric transfer function, which may
        change sign at low frequencies.
    """
    center = gaussian_blur_transfer(shape, sigma_center)
    surround = gaussian_blur_transfer(shape, sigma_surround)
    return center - float(surround_strength) * surround


def gaussian_field(spectrum: np.ndarray, n: int, rng: np.random.Generator) -> np.ndarray:
    """Draw real Gaussian random fields with an exact prescribed power spectrum.

    White real noise has a Hermitian transform, and ``spectrum`` is symmetric
    under ``f -> -f``, so shaping it in the Fourier domain and transforming back
    gives an exactly real field whose per-mode second moment is ``spectrum`` in
    the normalization of :func:`analysis.spectral_fillin.preprocess`.

    Args:
        spectrum (numpy.ndarray): Power spectrum shaped ``(height, width)``.
        n (int): Number of independent fields to draw.
        rng (numpy.random.Generator): Random generator.

    Returns:
        numpy.ndarray: Real fields shaped ``(n, height, width)``.
    """
    white = rng.normal(size=(n,) + spectrum.shape)
    shaped = np.fft.fft2(white) * np.sqrt(spectrum)[None]
    return np.fft.ifft2(shaped).real


@dataclass
class DiagonalPosterior:
    """An exact posterior sampler for ``Z = h * X + noise`` with circulant blur.

    Because the blur is a convolution and the prior is stationary, the posterior
    over ``X`` given ``Z`` is diagonal in the Fourier domain.  Per mode it is
    complex Gaussian with Wiener mean ``W(f) Zhat(f)`` and variance

        ``V(f) = P(f) N / (|H(f)|^2 P(f) + N)``,

    which can be rewritten as ``V(f) = P(f) / (1 + SNR(f))`` with
    ``SNR(f) = |H(f)|^2 P(f) / N``.  Since an exact posterior sampler reproduces
    the prior marginally, ``S_YY = P``, and the fill fraction is therefore
    exactly ``V / P = 1 / (1 + SNR(f))``.

    Attributes:
        shape (tuple[int, int]): Image shape.
        prior_spectrum (numpy.ndarray): Prior power spectrum ``P(f)``.
        transfer (numpy.ndarray): Blur transfer function ``H(f)``.
        noise_power (float): Observation noise power ``N``, flat across frequency.
        posterior_variance (numpy.ndarray): Per-mode posterior variance ``V(f)``.
        wiener (numpy.ndarray): Per-mode Wiener gain ``W(f)``.
        snr (numpy.ndarray): Per-mode observation SNR.
    """

    shape: tuple[int, int]
    prior_spectrum: np.ndarray
    transfer: np.ndarray
    noise_power: float
    posterior_variance: np.ndarray
    wiener: np.ndarray
    snr: np.ndarray

    def expected_fill_fraction(self) -> np.ndarray:
        """Return the exact per-mode fill fraction of a calibrated sampler.

        Returns:
            numpy.ndarray: ``1 / (1 + SNR(f))``, shaped like the image.
        """
        return 1.0 / (1.0 + self.snr)

    def draw_targets(self, n: int, rng: np.random.Generator) -> np.ndarray:
        """Draw target images from the prior.

        Args:
            n (int): Number of images.
            rng (numpy.random.Generator): Random generator.

        Returns:
            numpy.ndarray: Real images shaped ``(n, height, width)``.
        """
        return gaussian_field(self.prior_spectrum, n, rng)

    def encode(self, x: np.ndarray, rng: np.random.Generator) -> np.ndarray:
        """Apply the forward model to produce latent observations.

        Args:
            x (numpy.ndarray): Images shaped ``(n, height, width)``.
            rng (numpy.random.Generator): Random generator for observation noise.

        Returns:
            numpy.ndarray: Latent observations shaped like ``x``.
        """
        noise = gaussian_field(np.full(self.shape, self.noise_power), x.shape[0], rng)
        return np.fft.ifft2(np.fft.fft2(x) * self.transfer[None]).real + noise

    def sample(
        self,
        z: np.ndarray,
        n_samples: int,
        rng: np.random.Generator,
        noise_scale: float = 1.0,
        mean_scale: float = 1.0,
    ) -> np.ndarray:
        """Draw reconstructions from the posterior, optionally miscalibrated.

        The two scale factors are the two ways a guided sampler goes wrong, and
        the calibration diagnostics respond to them differently:

        * ``noise_scale = c`` scales the injected posterior noise.  Then
          ``S_YY = P + (c^2 - 1) V``, so ``S_YY / S_XX`` moves away from one,
          below for ``c < 1`` and above for ``c > 1``.  The cross ratio is
          **blind** to it, because scaling the noise leaves both ``S_XY`` and
          ``S_{Y_j Y_k}`` equal to ``P - V``.
        * ``mean_scale = g`` scales the Wiener mean, the stand-in for wrong
          guidance strength.  Then ``S_XY = g (P - V)`` while
          ``S_{Y_j Y_k} = g^2 (P - V)``, so the cross ratio is exactly ``1 / g``
          and detects it.

        Args:
            z (numpy.ndarray): Latent observations shaped ``(n, height, width)``.
            n_samples (int): Number of reconstructions per latent, K.
            rng (numpy.random.Generator): Random generator.
            noise_scale (float): Multiplier on the posterior standard deviation.
            mean_scale (float): Multiplier on the Wiener posterior mean.

        Returns:
            numpy.ndarray: Reconstructions shaped ``(n, n_samples, height, width)``.
        """
        n = z.shape[0]
        mean_hat = float(mean_scale) * self.wiener[None] * np.fft.fft2(z)
        mean = np.fft.ifft2(mean_hat).real
        variance = (float(noise_scale) ** 2) * self.posterior_variance
        samples = [mean + gaussian_field(variance, n, rng) for _ in range(n_samples)]
        return np.stack(samples, axis=1)


def make_diagonal_posterior(
    shape: tuple[int, int],
    prior_exponent: float = 2.0,
    blur_sigma: float = 2.0,
    noise_power: float | None = None,
    transfer: np.ndarray | None = None,
) -> DiagonalPosterior:
    """Build a linear-Gaussian toy retina with an exact Fourier-diagonal posterior.

    Args:
        shape (tuple[int, int]): Image shape as ``(height, width)``.
        prior_exponent (float): Power-law exponent of the prior spectrum.
        blur_sigma (float): Gaussian blur standard deviation in pixels, ignored
            when ``transfer`` is supplied.
        noise_power (float | None): Observation noise power; defaults to a value
            that puts the SNR crossover in the middle of the frequency range.
        transfer (numpy.ndarray | None): Explicit transfer function, for example
            from :func:`dog_transfer`.

    Returns:
        DiagonalPosterior: Toy model with its exact posterior quantities.
    """
    prior = power_law_spectrum(shape, prior_exponent)
    h = gaussian_blur_transfer(shape, blur_sigma) if transfer is None else np.asarray(transfer)
    if noise_power is None:
        noise_power = float(np.median(np.abs(h) ** 2 * prior))
    denominator = np.abs(h) ** 2 * prior + noise_power
    return DiagonalPosterior(
        shape=tuple(shape),
        prior_spectrum=prior,
        transfer=h,
        noise_power=float(noise_power),
        posterior_variance=prior * noise_power / denominator,
        wiener=np.conj(h) * prior / denominator,
        snr=np.abs(h) ** 2 * prior / noise_power,
    )


@dataclass
class DensePosterior:
    """An exact posterior sampler for a blur-then-subsample forward model.

    Subsampling is not a convolution, so the posterior is no longer diagonal in
    the Fourier domain: aliasing couples every frequency to its images under the
    sampling lattice.  There is therefore no closed form for the per-mode fill
    fraction, which is exactly why this toy is a qualitative overlay check rather
    than an analytic one.  The posterior is still Gaussian, so at small image
    sizes it can be formed exactly with dense linear algebra and sampled without
    approximation.

    Attributes:
        shape (tuple[int, int]): Image shape.
        prior_spectrum (numpy.ndarray): Prior power spectrum.
        spacing (int): Square sampling lattice spacing in pixels.
        noise_power (float): Observation noise variance per lattice site.
        prior_cov (numpy.ndarray): Dense prior covariance, ``(HW, HW)``.
        forward (numpy.ndarray): Dense forward operator, ``(n_sites, HW)``.
        posterior_mean_operator (numpy.ndarray): Maps observations to the posterior mean.
        posterior_chol (numpy.ndarray): Cholesky factor of the posterior covariance.
    """

    shape: tuple[int, int]
    prior_spectrum: np.ndarray
    spacing: int
    noise_power: float
    prior_cov: np.ndarray
    forward: np.ndarray
    posterior_mean_operator: np.ndarray
    posterior_chol: np.ndarray

    def draw_targets(self, n: int, rng: np.random.Generator) -> np.ndarray:
        """Draw target images from the prior.

        Args:
            n (int): Number of images.
            rng (numpy.random.Generator): Random generator.

        Returns:
            numpy.ndarray: Real images shaped ``(n, height, width)``.
        """
        return gaussian_field(self.prior_spectrum, n, rng)

    def encode(self, x: np.ndarray, rng: np.random.Generator) -> np.ndarray:
        """Blur, subsample, and add observation noise.

        Args:
            x (numpy.ndarray): Images shaped ``(n, height, width)``.
            rng (numpy.random.Generator): Random generator.

        Returns:
            numpy.ndarray: Observations shaped ``(n, n_sites)``.
        """
        flat = x.reshape(x.shape[0], -1)
        clean = flat @ self.forward.T
        return clean + np.sqrt(self.noise_power) * rng.normal(size=clean.shape)

    def sample(self, z: np.ndarray, n_samples: int, rng: np.random.Generator) -> np.ndarray:
        """Draw exact posterior samples given observations.

        Args:
            z (numpy.ndarray): Observations shaped ``(n, n_sites)``.
            n_samples (int): Number of reconstructions per observation, K.
            rng (numpy.random.Generator): Random generator.

        Returns:
            numpy.ndarray: Reconstructions shaped ``(n, n_samples, height, width)``.
        """
        n, d = z.shape[0], self.prior_cov.shape[0]
        mean = z @ self.posterior_mean_operator.T
        eps = rng.normal(size=(n, n_samples, d))
        samples = mean[:, None, :] + eps @ self.posterior_chol.T
        return samples.reshape(n, n_samples, *self.shape)


def make_downsampling_posterior(
    shape: tuple[int, int] = (32, 32),
    spacing: int = 4,
    blur_sigma: float = 1.5,
    prior_exponent: float = 2.0,
    noise_power: float | None = None,
    jitter: float = 1e-9,
) -> DensePosterior:
    """Build a blur-then-subsample toy with an exact dense Gaussian posterior.

    The forward model convolves with a periodic Gaussian kernel and then reads
    the result at the sites of a square lattice of the given spacing, which is
    the structure a retinal mosaic imposes.  The square lattice is used here
    rather than a hexagonal one so that the Nyquist overlay being checked is the
    unambiguous ``1 / (2 * spacing)``.

    Args:
        shape (tuple[int, int]): Image shape; keep it small, since the posterior
            is formed densely at ``(H * W)^2``.
        spacing (int): Lattice spacing in pixels; must divide both dimensions.
        blur_sigma (float): Gaussian blur standard deviation in pixels.
        prior_exponent (float): Power-law exponent of the prior spectrum.
        noise_power (float | None): Observation noise variance per site.
        jitter (float): Diagonal loading added before the Cholesky factorization.

    Returns:
        DensePosterior: Toy model with its exact dense posterior.
    """
    height, width = shape
    if height % spacing or width % spacing:
        raise ValueError("The lattice spacing must divide both image dimensions.")
    prior = power_law_spectrum(shape, prior_exponent)

    # Dense stationary prior covariance: the autocovariance is the inverse
    # transform of the power spectrum, evaluated at the wrapped pixel lag.
    autocov = np.fft.ifft2(prior).real
    yy, xx = np.meshgrid(np.arange(height), np.arange(width), indexing="ij")
    coords = np.stack([yy.ravel(), xx.ravel()], axis=1)
    lag_y = (coords[:, None, 0] - coords[None, :, 0]) % height
    lag_x = (coords[:, None, 1] - coords[None, :, 1]) % width
    prior_cov = autocov[lag_y, lag_x]

    # Dense forward operator: one row per lattice site, holding the periodic
    # blur kernel recentred on that site.
    kernel = np.fft.ifft2(gaussian_blur_transfer(shape, blur_sigma)).real
    sites = [(sy, sx) for sy in range(0, height, spacing) for sx in range(0, width, spacing)]
    forward = np.stack(
        [np.roll(np.roll(kernel, sy, axis=0), sx, axis=1).ravel() for sy, sx in sites], axis=0
    )

    if noise_power is None:
        noise_power = float(np.mean(np.diag(forward @ prior_cov @ forward.T)) * 1e-2)

    cross = prior_cov @ forward.T
    observation_cov = forward @ cross + noise_power * np.eye(len(sites))
    gain = np.linalg.solve(observation_cov, cross.T).T
    posterior_cov = prior_cov - gain @ cross.T
    posterior_cov = 0.5 * (posterior_cov + posterior_cov.T)
    scale = float(np.trace(posterior_cov) / posterior_cov.shape[0])
    chol = np.linalg.cholesky(posterior_cov + jitter * scale * np.eye(posterior_cov.shape[0]))
    return DensePosterior(
        shape=tuple(shape),
        prior_spectrum=prior,
        spacing=int(spacing),
        noise_power=float(noise_power),
        prior_cov=prior_cov,
        forward=forward,
        posterior_mean_operator=gain,
        posterior_chol=chol,
    )
